export const DEFAULT_MAP = 'sumperk';

// Vybere mapu podle polohy: tu, ve které hráč je, jinak nejbližší (podle středu území)
export function pickArea(lat, lng) {
  const all = Object.values(MAPS);
  const inside = all.find((m) => isInside([lat, lng], m.boundary));
  if (inside) return inside;
  const center = (m) => [
    m.boundary.reduce((s, p) => s + p[0], 0) / m.boundary.length,
    m.boundary.reduce((s, p) => s + p[1], 0) / m.boundary.length,
  ];
  const km = (a, b) => Math.hypot((a[0] - b[0]) * 111.32, (a[1] - b[1]) * 71.7);
  return all.reduce((best, m) => (km([lat, lng], center(m)) < km([lat, lng], center(best)) ? m : best));
}

export const getArea = (id) => MAPS[id] || MAPS[DEFAULT_MAP];
